// Physical page relative to a period-aligned base.
// measured_AID(p) = kAidPat[(p + rot) % 1792], so the k-th AID-a page is
// (kAid*Off[k % n] - rot) mod 1792, plus 1792 * (k / n).
__host__ __device__ inline uint32_t aid_nth_page(int aid, int logical, int rot) {
  int const n = aid ? kAid1PerPeriod : kAid0PerPeriod;
  int const q = aid ? (int)kAid1Off[logical % n] : (int)kAid0Off[logical % n];
  int const r = ((rot % kAidPeriod) + kAidPeriod) % kAidPeriod;
  return (uint32_t)(logical / n) * (uint32_t)kAidPeriod +
         (uint32_t)((q + kAidPeriod - r) % kAidPeriod);
}
